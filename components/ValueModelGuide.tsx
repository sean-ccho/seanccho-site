/** 간단한 표 — right 에 넣은 열 번호는 오른쪽 정렬 숫자. */
function Tbl({ head, rows, right = [] }: { head: string[]; rows: ReactNode[][]; right?: number[] }) {
  return (
    <div className="table-wrap">
      <table className="data-table data-table--tight">
        <thead>
          <tr>{head.map((h, i) => <th key={i} className={right.includes(i) ? "r" : undefined}>{h}</th>)}</tr>
        </thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={i}>
              {r.map((c, j) => <td key={j} className={right.includes(j) ? "r num" : undefined}>{c}</td>)}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

