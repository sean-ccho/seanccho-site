/** 한국어 라벨 하나 → 지금 언어 (모르는 말은 그대로). */
export function term(lang: Lang, s: string | null | undefined): string {
  if (!s) return "";
  return lang === "en" ? (TERMS_EN[s] ?? s) : s;
}

/** '시간익절(12일,+15.9%)' · '교체→ANET' 같은 청산 사유. */
export function exitReason(lang: Lang, s: string | null | undefined): string {
  if (!s) return "—";
  if (lang === "ko") return s;
  const m = s.match(/^(목표가|시간익절|트레일링|손절|장기보유|교체)(.*)$/);
  if (!m) return s;
  const rest = m[2].replace(/(\d+)일/g, "$1d").replace(/,/g, ", ");
  return `${TERMS_EN[m[1]]}${rest.startsWith("(") ? ` ${rest}` : rest}`;
}

/** 헬스체크 설명 '매출+16% 마진+20% 이익+33%'. */
export function healthDetail(lang: Lang, s: string | null | undefined): string {
  if (!s) return "";
  if (lang === "ko") return s;
  return s.replace(/매출/g, "Rev ").replace(/마진/g, "Margin ").replace(/이익/g, "EPS ");
}

