/** '시간익절(12일,+15.9%)' · '교체→ANET' 같은 청산 사유. */
export function exitReason(lang: Lang, s: string | null | undefined): string {
  if (!s) return "—";
  if (lang === "ko") return s;
  const m = s.match(/^(목표가|시간익절|트레일링|손절|장기보유|교체)(.*)$/);
  if (!m) return s;
  const rest = m[2].replace(/(\d+)일/g, "$1d").replace(/,/g, ", ");
  return `${TERMS_EN[m[1]]}${rest.startsWith("(") ? ` ${rest}` : rest}`;
}

